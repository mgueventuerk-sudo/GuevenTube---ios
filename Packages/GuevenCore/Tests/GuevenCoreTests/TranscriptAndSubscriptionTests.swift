import XCTest
@testable import GuevenCore

final class TranscriptTests: XCTestCase {
    func testParsesJson3Events() {
        let body = #"{"events":[{"tStartMs":0,"dDurationMs":10},{"tStartMs":1200,"segs":[{"utf8":"Hallo "},{"utf8":"Welt"}]},{"tStartMs":3400,"segs":[{"utf8":"\n"}]},{"tStartMs":5000,"segs":[{"utf8":"zweite\nZeile"}]}]}"#
        XCTAssertEqual(Transcript.parseJson3(body), [TranscriptLine(startMs: 1200, text: "Hallo Welt"), TranscriptLine(startMs: 5000, text: "zweite Zeile")])
    }

    func testBrokenOrUnexpectedShapesNeverCrash() {
        XCTAssertEqual(Transcript.parseJson3("[]"), [])
        XCTAssertEqual(Transcript.parseJson3("kein json"), [])
        XCTAssertEqual(Transcript.parseJson3(#"{"events":"x"}"#), [])
        let odd = #"{"events":[1,"a",{"tStartMs":"abc","segs":[]},{"tStartMs":10,"segs":[{"utf8":5},{"utf8":"ok"},"x"]},{"tStartMs":20,"segs":"kaputt"}]}"#
        XCTAssertEqual(Transcript.parseJson3(odd), [TranscriptLine(startMs: 10, text: "ok")])
    }

    func testSearchNeedsTwoCharactersIgnoresCaseAndCaps() {
        let lines = [TranscriptLine(startMs: 0, text: "Kotlin ist toll"), TranscriptLine(startMs: 1, text: "Java auch")]
        XCTAssertEqual(Transcript.search(lines, "k"), [])
        XCTAssertEqual(Transcript.search(lines, " KOT "), [lines[0]])
        let many = (0..<80).map { TranscriptLine(startMs: Int64($0), text: "treffer \($0)") }
        XCTAssertEqual(Transcript.search(many, "treffer").count, Transcript.maxResults)
    }

    func testPickTrackPrefersManualInLanguageThenAnyManualThenAuto() {
        func track(_ lang: String, auto: Bool) -> CaptionTrack { CaptionTrack(baseUrl: "u-\(lang)-\(auto)", languageCode: lang, name: lang, isAutoGenerated: auto) }
        let all = [track("de", auto: true), track("en", auto: false), track("de-DE", auto: false)]
        XCTAssertEqual(Transcript.pickTrack(all, preferredLanguage: nil)?.languageCode, "de-DE")
        XCTAssertEqual(Transcript.pickTrack(all, preferredLanguage: "en")?.languageCode, "en")
        XCTAssertEqual(Transcript.pickTrack(all, preferredLanguage: "fr")?.languageCode, "en")
        XCTAssertEqual(Transcript.pickTrack([track("de", auto: true)], preferredLanguage: "de")?.isAutoGenerated, true)
        XCTAssertNil(Transcript.pickTrack([], preferredLanguage: nil))
    }

    func testJson3URLAppendsFormat() {
        let t = CaptionTrack(baseUrl: "https://www.youtube.com/api/timedtext?v=abc&lang=de", languageCode: "de", name: "", isAutoGenerated: false)
        XCTAssertEqual(Transcript.json3URL(t)?.absoluteString, "https://www.youtube.com/api/timedtext?v=abc&lang=de&fmt=json3")
    }
}

final class TranscriptSummarizerTests: XCTestCase {
    private func line(_ sec: Int64, _ text: String) -> TranscriptLine { TranscriptLine(startMs: sec * 1000, text: text) }
    private var lines: [TranscriptLine] { [
        line(0, "Hallo und willkommen zu diesem Video über Akkus."),
        line(4, "Heute testen wir den neuen Akku im Elektroauto."),
        line(9, "Der Akku hat eine Kapazität von achtzig Kilowattstunden."),
        line(15, "Übrigens, das Wetter war heute schön."),
        line(20, "Beim Laden erreicht der Akku in zwanzig Minuten achtzig Prozent."),
        line(26, "Die Reichweite des Elektroauto liegt bei fünfhundert Kilometern."),
        line(32, "Danke fürs Zuschauen."),
    ] }

    func testSummaryPrefersKeyTermsAndKeepsOrder() {
        let points = TranscriptSummarizer.summarize(lines, maxPoints: 3)
        XCTAssertEqual(points.count, 3)
        XCTAssertTrue(zip(points, points.dropFirst()).allSatisfy { $0.startMs < $1.startMs })
        XCTAssertGreaterThanOrEqual(points.filter { $0.text.contains("Akku") }.count, 2)
        XCTAssertTrue(points.allSatisfy { !$0.text.contains("Wetter") })
    }

    func testFragmentsAreJoinedIntoSentences() {
        let joined = TranscriptSummarizer.sentences([line(0, "Das ist"), line(1, "ein Satz."), line(10, "Und der nächste")])
        XCTAssertEqual(joined.map(\.text), ["Das ist ein Satz.", "Und der nächste"])
    }

    func testBracketedSoundCuesAreDropped() {
        let s = TranscriptSummarizer.sentences([line(0, "[Musik]"), line(1, "Hallo [Applaus] Welt.")])
        XCTAssertEqual(s.map(\.text), ["Hallo   Welt."])
    }

    func testChaptersCoverLongVideosWithKeywords() {
        let long: [TranscriptLine] = stride(from: 0, to: 600, by: 10).map { s in
            let topic = s < 200 ? "Motor Leistung Motor" : s < 400 ? "Batterie Ladung Batterie" : "Fazit Preis Fazit"
            return line(Int64(s), "\(topic) im Test.")
        }
        let chapters = TranscriptSummarizer.chapters(long, durationMs: 600_000)
        XCTAssertEqual(chapters.count, 3)
        XCTAssertEqual(chapters.first?.startMs, 0)
        XCTAssertTrue(chapters[0].title.contains("Motor"))
        XCTAssertTrue(chapters[1].title.contains("Batterie"))
        XCTAssertTrue(chapters[2].title.contains("Fazit"))
    }

    func testShortVideosGetNoChaptersAndEmptyInputIsSafe() {
        XCTAssertTrue(TranscriptSummarizer.chapters(lines, durationMs: 60_000).isEmpty)
        XCTAssertTrue(TranscriptSummarizer.summarize([]).isEmpty)
        XCTAssertTrue(TranscriptSummarizer.chapters([], durationMs: 900_000).isEmpty)
    }

    func testWordsAreLowercasedStopwordFreeAndUnicodeAware() {
        XCTAssertEqual(TranscriptSummarizer.words("Der Käse und die Ärzte, 2024!"), ["käse", "ärzte", "2024"])
    }
}

final class SubscriptionOrderTests: XCTestCase {
    private func channel(_ id: String, _ name: String) -> SubscribedChannel { SubscribedChannel(channelId: id, name: name, avatarUrl: nil, hasNewContent: false) }
    private var dir: URL!
    override func setUpWithError() throws { dir = FileManager.default.temporaryDirectory.appendingPathComponent("sub-\(UUID().uuidString)") }
    override func tearDown() { try? FileManager.default.removeItem(at: dir) }

    func testRecentlySubscribedPutsNewFirstAndKeepsYouTubeOrderForInitialSet() async throws {
        let store = SubscriptionDatesStore(directory: dir)
        let initial = [channel("UC1", "Bravo"), channel("UC2", "alpha"), channel("UC3", "Charlie")]
        let firstRun = try await store.firstSeen(accountKey: "acc", channelIds: initial.map(\.channelId), now: 1_000)
        let later = [channel("UC4", "Delta")] + initial
        let secondRun = try await store.firstSeen(accountKey: "acc", channelIds: later.map(\.channelId), now: 2_000)
        XCTAssertEqual(secondRun["UC1"], 1_000)
        XCTAssertEqual(secondRun["UC4"], 2_000)
        let recent = sortSubscribedChannels(Array(later.reversed()), sort: .recentlySubscribed, firstSeen: secondRun)
        XCTAssertEqual(recent.map(\.name), ["Delta", "Charlie", "alpha", "Bravo"])
        XCTAssertEqual(firstRun.count, 3)
        let pruned = try await store.firstSeen(accountKey: "acc", channelIds: ["UC1"], now: 3_000)
        XCTAssertEqual(pruned, ["UC1": 1_000])
    }

    func testAlphabeticalIgnoresCaseAndAccentsAndYouTubeOrderIsUnchanged() {
        let list = [channel("a", "Zeta"), channel("b", "äpfel"), channel("c", "Beta")]
        XCTAssertEqual(sortSubscribedChannels(list, sort: .alphabetical, firstSeen: [:], locale: Locale(identifier: "de")).map(\.name), ["äpfel", "Beta", "Zeta"])
        XCTAssertEqual(sortSubscribedChannels(list, sort: .youtube, firstSeen: [:]), list)
        XCTAssertEqual(SubscriptionSort.youtube.next(), .recentlySubscribed)
        XCTAssertEqual(SubscriptionSort.alphabetical.next(), .youtube)
    }

    func testInvalidAccountKeyIsRejectedAndCorruptFileStartsOver() async throws {
        let store = SubscriptionDatesStore(directory: dir)
        do { _ = try await store.firstSeen(accountKey: "../böse", channelIds: [], now: 1); XCTFail("hätte abgelehnt werden müssen") }
        catch { XCTAssertEqual(error as? InvalidAccountKey, InvalidAccountKey()) }
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        try Data("{kaputt".utf8).write(to: dir.appendingPathComponent("acc.json"))
        let r = try await store.firstSeen(accountKey: "acc", channelIds: ["UC1"], now: 5)
        XCTAssertEqual(r, ["UC1": 5])
    }
}
