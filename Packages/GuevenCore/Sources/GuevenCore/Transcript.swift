import Foundation

/// Eine Zeile des Transkripts.
public struct TranscriptLine: Equatable, Hashable, Sendable {
    public var startMs: Int64
    public var text: String
    public init(startMs: Int64, text: String) { self.startMs = startMs; self.text = text }
}

/// Transkript aus den Untertiteln: „Suche im Video“ findet Begriffe und springt zur Stelle (Port von TranscriptRepository.kt).
public enum Transcript {
    public static let maxResults = 50

    /// Bevorzugt eine echte Untertitelspur in [preferredLanguage], sonst die automatische.
    public static func pickTrack(_ captions: [CaptionTrack], preferredLanguage: String?) -> CaptionTrack? {
        let language = preferredLanguage ?? "de"
        return captions.first { $0.languageCode.hasPrefix(language) && !$0.isAutoGenerated }
            ?? captions.first { !$0.isAutoGenerated }
            ?? captions.first
    }

    /// Adresse für das json3-Format (hängt `fmt=json3` an).
    public static func json3URL(_ track: CaptionTrack) -> URL? {
        guard var c = URLComponents(string: track.baseUrl) else { return nil }
        var items = c.queryItems ?? []
        items.append(URLQueryItem(name: "fmt", value: "json3"))
        c.queryItems = items
        return c.url
    }

    public static func search(_ lines: [TranscriptLine], _ query: String) -> [TranscriptLine] {
        let needle = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard needle.utf16.count >= 2 else { return [] }
        return Array(lines.filter { $0.text.range(of: needle, options: .caseInsensitive) != nil }.prefix(maxResults))
    }

    /// Nur sichere Zugriffe: unerwartete Typen führen zu „überspringen“, nie zum Absturz.
    public static func parseJson3(_ body: String) -> [TranscriptLine] {
        guard let root = try? JSONParser.parse(body), root.objectValue != nil, let events = root.arr("events") else { return [] }
        return events.compactMap { event in
            guard event.objectValue != nil, let start = event.long("tStartMs") else { return nil }
            guard let segs = event.arr("segs") else { return nil }
            let joined = segs.map { seg -> String in
                if case .string(let s)? = seg.objectValue?["utf8"] { return s }
                return ""
            }.joined()
            let text = joined.replacingOccurrences(of: "\n", with: " ").trimmingCharacters(in: .whitespacesAndNewlines)
            return text.isEmpty ? nil : TranscriptLine(startMs: start, text: text)
        }
    }
}

/// Kurzfassung und Kapitel aus dem Transkript – vollständig auf dem Gerät, ohne Netz und KI-Dienst: Sätze werden nach
/// der Häufigkeit ihrer bedeutungstragenden Wörter bewertet, Kapitel entstehen aus gleich langen Abschnitten.
public enum TranscriptSummarizer {
    public struct Point: Equatable, Sendable { public var startMs: Int64; public var text: String }
    public struct Chapter: Equatable, Sendable { public var startMs: Int64; public var title: String }

    private static let minWords = 4
    private static let pauseMs: Int64 = 2_500
    private static let maxSentence = 240
    private static let minChapterVideoMs: Int64 = 4 * 60 * 1000
    private static let targetChapterMs: Int64 = 3 * 60 * 1000
    private static let maxChapters = 8

    /// Höchstens [maxPoints] Kernsätze in zeitlicher Reihenfolge.
    public static func summarize(_ lines: [TranscriptLine], maxPoints: Int = 5) -> [Point] {
        let sentences = Self.sentences(lines)
        if sentences.count <= maxPoints { return sentences.filter { words($0.text).count >= minWords } }
        var frequency = OrderedCounter()
        for s in sentences { for w in words(s.text) { frequency.add(w) } }
        guard let top = frequency.maxCount.map(Double.init) else { return [] }
        let scored: [(offset: Int, point: Point, score: Double)] = sentences.enumerated().map { i, sentence in
            let tokens = words(sentence.text)
            let score = tokens.count < minWords ? 0.0 : tokens.reduce(0.0) { $0 + Double(frequency[$1]) / top } / log(Double(tokens.count) + 1.0)
            return (i, sentence, score)
        }
        return scored
            .sorted { $0.score != $1.score ? $0.score > $1.score : $0.offset < $1.offset }   // stabil, absteigend
            .prefix(maxPoints)
            .filter { $0.score > 0 }
            .map(\.point)
            .enumerated().sorted { $0.element.startMs != $1.element.startMs ? $0.element.startMs < $1.element.startMs : $0.offset < $1.offset }
            .map(\.element)
    }

    /// Kapitel für Videos ohne eigene Kapitel: Abschnitte aus der Länge abgeleitet, Titel aus Schlüsselwörtern.
    public static func chapters(_ lines: [TranscriptLine], durationMs: Int64) -> [Chapter] {
        if lines.isEmpty || durationMs < minChapterVideoMs { return [] }
        let count = Int(min(max(durationMs / targetChapterMs, 3), Int64(maxChapters)))
        let window = durationMs / Int64(count)
        let groups: [[TranscriptLine]] = (0..<count).map { index in
            lines.filter { $0.startMs >= Int64(index) * window && $0.startMs < Int64(index + 1) * window }
        }
        let documents = groups.map { $0.flatMap { words($0.text) } }
        var documentFrequency = OrderedCounter()
        for d in documents { var seen = Set<String>(); for w in d where seen.insert(w).inserted { documentFrequency.add(w) } }
        var result: [Chapter] = []
        var usedStarts = Set<Int64>()
        for (index, group) in groups.enumerated() {
            guard let first = group.first else { continue }
            var tf = OrderedCounter()
            for w in documents[index] { tf.add(w) }
            let ranked = tf.entries.enumerated().map { i, e -> (i: Int, word: String, score: Double) in
                let df = max(documentFrequency[e.key], 1)
                return (i, e.key, Double(e.value) * log(Double(count) / Double(df)) + Double(e.value) * 0.01)
            }.sorted { $0.score != $1.score ? $0.score > $1.score : $0.i < $1.i }
            let keywords = ranked.prefix(2).map { titlecased($0.word) }
            let title = keywords.isEmpty ? "Teil \(index + 1)" : keywords.joined(separator: " & ")
            let start = index == 0 ? 0 : first.startMs
            if usedStarts.insert(start).inserted { result.append(Chapter(startMs: start, title: title)) }
        }
        return result
    }

    /// Fragmente zu Sätzen zusammenfügen (Satzzeichen oder Pause von > 2,5 s).
    static func sentences(_ lines: [TranscriptLine]) -> [Point] {
        var result: [Point] = []
        var current = ""
        var start: Int64 = 0, last: Int64 = 0
        for line in lines {
            let text = line.text.replacingOccurrences(of: "\\[[^\\]]*\\]", with: " ", options: .regularExpression)
                .trimmingCharacters(in: .whitespacesAndNewlines)
            if text.isEmpty { continue }
            if !current.isEmpty && line.startMs - last > pauseMs {
                result.append(Point(startMs: start, text: current.trimmingCharacters(in: .whitespacesAndNewlines)))
                current = ""
            }
            if current.isEmpty { start = line.startMs }
            current += text + " "
            last = line.startMs
            if text.hasSuffix(".") || text.hasSuffix("!") || text.hasSuffix("?") || current.utf16.count > maxSentence {
                result.append(Point(startMs: start, text: current.trimmingCharacters(in: .whitespacesAndNewlines)))
                current = ""
            }
        }
        if !current.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            result.append(Point(startMs: start, text: current.trimmingCharacters(in: .whitespacesAndNewlines)))
        }
        return result
    }

    static func words(_ text: String) -> [String] {
        var tokens: [String] = []
        var current = ""
        for scalar in text.lowercased().unicodeScalars {
            if scalar.properties.isAlphabetic || scalar.properties.numericType != nil { current.unicodeScalars.append(scalar) }
            else if !current.isEmpty { tokens.append(current); current = "" }
        }
        if !current.isEmpty { tokens.append(current) }
        return tokens.filter { $0.utf16.count > 2 && !stopwords.contains($0) }
    }

    private static func titlecased(_ word: String) -> String { word.prefix(1).uppercased() + word.dropFirst() }

    /// Zähler, der die Reihenfolge des ersten Auftretens behält (wie `groupingBy().eachCount()` auf einer `LinkedHashMap`).
    private struct OrderedCounter {
        private(set) var entries: [(key: String, value: Int)] = []
        private var index: [String: Int] = [:]
        mutating func add(_ key: String) {
            if let i = index[key] { entries[i].value += 1 } else { index[key] = entries.count; entries.append((key, 1)) }
        }
        subscript(key: String) -> Int { index[key].map { entries[$0].value } ?? 0 }
        var maxCount: Int? { entries.map(\.value).max() }
    }

    private static let stopwords: Set<String> = [
        // Deutsch
        "und", "oder", "aber", "der", "die", "das", "den", "dem", "des", "ein", "eine", "einen", "einem", "einer", "eines",
        "ich", "du", "er", "sie", "es", "wir", "ihr", "mich", "dich", "sich", "uns", "euch", "mir", "dir", "ihm", "ihn",
        "ist", "sind", "war", "waren", "bin", "bist", "hat", "haben", "habe", "hast", "wird", "werden", "wurde", "kann", "können",
        "nicht", "auch", "noch", "schon", "nur", "mal", "dann", "also", "jetzt", "hier", "da", "so", "wie", "was", "wenn",
        "mit", "von", "für", "auf", "aus", "bei", "nach", "über", "unter", "vor", "zum", "zur", "im", "in", "am", "an", "zu",
        "dass", "weil", "denn", "doch", "ja", "nein", "sehr", "mehr", "viel", "ganz", "einfach", "genau", "gibt", "macht",
        "man", "dieser", "diese", "dieses", "diesen", "alle", "alles", "etwas", "wirklich", "eigentlich", "halt", "eben", "okay",
        // Englisch
        "the", "and", "for", "you", "that", "this", "with", "are", "was", "but", "not", "have", "has", "had", "they", "she",
        "his", "her", "its", "our", "your", "their", "from", "what", "when", "where", "which", "who", "will", "would", "can",
        "could", "should", "just", "like", "really", "know", "going", "get", "got", "yeah", "there", "here", "then", "than",
        "about", "into", "out", "all", "some", "one", "two", "very", "also", "because", "been", "being", "were", "did", "does",
    ]
}
